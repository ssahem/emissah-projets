-- ==============================================================================
-- V3__tracabilite.sql — journal de réouverture (F15) et alertes (F16)
--
-- Aucune clé étrangère supplémentaire n'est introduite vers note ou trimestre
-- (arbitrages A-01 à A-05). L'auteur de la réouverture est un texte libre fourni
-- par l'appelant : l'API n'a aucun utilisateur authentifié.
-- ==============================================================================

CREATE TABLE historique_reouverture_trimestre (
    id_historique integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trimestre integer NOT NULL,
    date_reouverture date NOT NULL,
    motif text NOT NULL,
    auteur character varying NOT NULL,
    CONSTRAINT uq_reouverture_trimestre UNIQUE (id_trimestre),
    CONSTRAINT fk_reouverture_trimestre FOREIGN KEY (id_trimestre) REFERENCES trimestre (id_trimestre)
);

CREATE TABLE alerte_difficulte (
    id_alerte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscription integer NOT NULL,
    numero_trimestre integer NOT NULL,
    moyenne numeric NOT NULL,
    ecart numeric NOT NULL,
    date_alerte date NOT NULL,
    CONSTRAINT uq_alerte_inscription_trimestre UNIQUE (id_inscription, numero_trimestre),
    CONSTRAINT fk_alerte_inscription FOREIGN KEY (id_inscription) REFERENCES inscription (id_inscription)
);
