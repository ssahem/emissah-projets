-- E-06 : historique des loyers. La première révision est datée du début du bail,
-- ce qui rend F15 (révision postérieure au début) et F18 possibles.
-- bail.loyer_mensuel reste la valeur courante, mise à jour dans la même transaction.

CREATE TABLE revision_loyer (
    id_revision INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bail INTEGER NOT NULL REFERENCES bail(id_bail),
    date_effet DATE NOT NULL,
    montant NUMERIC NOT NULL,
    CONSTRAINT ck_revision_loyer_montant CHECK (montant > 0),
    CONSTRAINT uq_revision_loyer_bail_date UNIQUE (id_bail, date_effet)
);

INSERT INTO revision_loyer (id_bail, date_effet, montant)
SELECT id_bail, date_debut, loyer_mensuel FROM bail;
