-- E-05 : traçabilité des changements de date de fin et de statut d'un bail.
-- Utilisé par F13 (RESILIATION), F14 (RENOUVELLEMENT) et F16 (CLOTURE).
-- Pas de UNIQUE sur (id_bail, motif, date_evenement) : résiliation puis clôture
-- peuvent survenir le même jour.

CREATE TABLE historique_bail (
    id_historique INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bail INTEGER NOT NULL REFERENCES bail(id_bail),
    motif VARCHAR(20) NOT NULL,
    date_evenement DATE NOT NULL DEFAULT CURRENT_DATE,
    date_fin_avant DATE,
    date_fin_apres DATE,
    CONSTRAINT ck_historique_bail_motif
        CHECK (motif IN ('RESILIATION', 'RENOUVELLEMENT', 'CLOTURE'))
);

CREATE INDEX ix_historique_bail_bail ON historique_bail(id_bail, date_evenement);
