CREATE TABLE categorie (
    id_categorie integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle      varchar(20) NOT NULL,
    CONSTRAINT uk_categorie_libelle UNIQUE (libelle)
);

CREATE TABLE client (
    id_client integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom       varchar(100) NOT NULL,
    prenom    varchar(100) NOT NULL,
    email     varchar(255) NOT NULL,
    CONSTRAINT uk_client_email UNIQUE (email)
);

CREATE TABLE salle (
    id_salle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom      varchar(100) NOT NULL,
    adresse  varchar(255) NOT NULL,
    capacite integer NOT NULL,
    CONSTRAINT ck_salle_capacite CHECK (capacite > 0)
);

CREATE TABLE spectacle (
    id_spectacle       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre              varchar(150) NOT NULL,
    type               varchar(20) NOT NULL,
    placement_numerote boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_spectacle_type CHECK (type IN ('CONCERT', 'THEATRE', 'CONFERENCE'))
);

CREATE TABLE evenement (
    id_evenement integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_heure   timestamp NOT NULL,
    id_spectacle integer NOT NULL,
    id_salle     integer NOT NULL,
    CONSTRAINT fk_evenement_spectacle FOREIGN KEY (id_spectacle) REFERENCES spectacle(id_spectacle),
    CONSTRAINT fk_evenement_salle FOREIGN KEY (id_salle) REFERENCES salle(id_salle)
);
CREATE INDEX ix_evenement_date_heure ON evenement(date_heure);

CREATE TABLE place (
    id_place     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rang         varchar(5) NOT NULL,
    numero       integer NOT NULL,
    id_salle     integer NOT NULL,
    id_categorie integer NOT NULL,
    CONSTRAINT uk_place_salle_rang_numero UNIQUE (id_salle, rang, numero),
    CONSTRAINT ck_place_numero CHECK (numero > 0),
    CONSTRAINT fk_place_salle FOREIGN KEY (id_salle) REFERENCES salle(id_salle),
    CONSTRAINT fk_place_categorie FOREIGN KEY (id_categorie) REFERENCES categorie(id_categorie)
);

CREATE TABLE statut (
    id_statut integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle   varchar(30) NOT NULL,
    CONSTRAINT uk_statut_libelle UNIQUE (libelle)
);

CREATE TABLE reservation (
    id_reservation    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_creation     timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
    date_expiration   timestamp NOT NULL DEFAULT (LOCALTIMESTAMP + interval '15 minutes'),
    id_client         integer NOT NULL,
    id_evenement      integer NOT NULL,
    montant_rembourse numeric(12,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_reservation_montant_rembourse CHECK (montant_rembourse >= 0),
    CONSTRAINT fk_reservation_client FOREIGN KEY (id_client) REFERENCES client(id_client),
    CONSTRAINT fk_reservation_evenement FOREIGN KEY (id_evenement) REFERENCES evenement(id_evenement)
);
CREATE INDEX ix_reservation_client ON reservation(id_client);
CREATE INDEX ix_reservation_evenement ON reservation(id_evenement);

CREATE TABLE reservation_place (
    id_reservation_place integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reservation       integer NOT NULL,
    rang                 varchar(5),
    numero               integer,
    prix_applique        numeric(12,2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_reservation_place UNIQUE (id_reservation, rang, numero),
    CONSTRAINT ck_reservation_place CHECK ((rang IS NULL) = (numero IS NULL)),
    CONSTRAINT ck_reservation_place_prix CHECK (prix_applique >= 0),
    CONSTRAINT fk_reservation_place_reservation FOREIGN KEY (id_reservation) REFERENCES reservation(id_reservation)
);
CREATE INDEX ix_reservation_place_reservation ON reservation_place(id_reservation);

CREATE TABLE tarif (
    id_tarif     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evenement integer NOT NULL,
    categorie    varchar(10) NOT NULL,
    prix         numeric(12,2) NOT NULL,
    CONSTRAINT uk_tarif_evenement_categorie UNIQUE (id_evenement, categorie),
    CONSTRAINT ck_tarif_categorie CHECK (categorie IN ('ORCHESTRE', 'BALCON', 'LOGE')),
    CONSTRAINT ck_tarif_prix CHECK (prix >= 0),
    CONSTRAINT fk_tarif_evenement FOREIGN KEY (id_evenement) REFERENCES evenement(id_evenement)
);

CREATE TABLE historique_statut (
    id_reservation integer NOT NULL,
    id_statut      integer NOT NULL,
    date_statut    timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
    PRIMARY KEY (id_reservation, id_statut),
    CONSTRAINT fk_historique_reservation FOREIGN KEY (id_reservation) REFERENCES reservation(id_reservation),
    CONSTRAINT fk_historique_statut FOREIGN KEY (id_statut) REFERENCES statut(id_statut)
);

CREATE VIEW v_historique_reservation AS
SELECT h.id_reservation, s.libelle AS statut, h.date_statut
FROM historique_statut h JOIN statut s ON s.id_statut = h.id_statut;

CREATE VIEW v_reservation_statut AS
SELECT r.id_reservation, r.id_client, r.id_evenement,
       (SELECT s.libelle
          FROM historique_statut h JOIN statut s ON s.id_statut = h.id_statut
         WHERE h.id_reservation = r.id_reservation
         ORDER BY h.date_statut DESC LIMIT 1)::text AS statut
FROM reservation r;
