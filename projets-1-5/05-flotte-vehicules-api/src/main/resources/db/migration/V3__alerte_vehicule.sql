-- ==============================================================================
-- V3__alerte_vehicule.sql — persistance des alertes (décision A-02)
--
-- Une seule clé étrangère, vers affectation. id_vehicule est une colonne simple
-- (pas de FK) afin de pouvoir alerter un véhicule sans affectation en cours.
-- L'unicité (id_vehicule, motif, date_echeance) garantit la traçabilité de F16 :
-- un véhicule déjà signalé pour une échéance n'est pas signalé une seconde fois
-- avant son entretien ; un nouvel entretien décale l'échéance et permet une
-- nouvelle alerte. Le même stockage sert aux alertes de conflit de F12.
-- ==============================================================================

CREATE TABLE alerte_vehicule (
    id_alerte integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT alerte_vehicule_pkey PRIMARY KEY,
    id_affectation integer CONSTRAINT alerte_vehicule_id_affectation_fkey REFERENCES affectation(id_affectation),
    id_vehicule integer NOT NULL,
    motif character varying NOT NULL,
    periode character varying NOT NULL,
    date_alerte date NOT NULL,
    date_echeance date NOT NULL,
    ecart_km integer,
    ecart_jours integer,
    detail character varying,
    CONSTRAINT uq_alerte_vehicule UNIQUE (id_vehicule, motif, date_echeance)
);
